"""Generate the Windows installer script from the shared Inno Setup layout."""

import sys
from pathlib import Path, PureWindowsPath


def _escape_inno(value: str) -> str:
    return value.replace('"', '""')


def generate_inno_iss(
    target: Path,
    version_define: str,
    app_name: str,
    app_publisher: str,
    app_icon: str,
    app_exe: str,
    default_dir_name: str,
    default_group_name: str,
    output_dir: str,
    output_base_filename: str,
    compression: str,
    solid_compression: str,
    app_version: str,
) -> int:
    try:
        values = {
            "MyAppName": app_name,
            version_define: app_version,
            "MyAppPublisher": app_publisher,
            "MyAppExe": app_exe.replace("/", "\\"),
            "MyAppExeName": PureWindowsPath(app_exe).name,
            "MyAppIcon": app_icon.replace("/", "\\"),
            "MyAppDefaultDirName": default_dir_name,
            "MyAppDefaultGroupName": default_group_name,
            "MyAppOutputDir": output_dir.replace("/", "\\"),
            "MyAppOutputBaseFilename": output_base_filename,
            "MyAppCompression": compression,
            "MyAppSolidCompression": solid_compression,
        }
        layout = Path(__file__).with_name("templates") / "installer.iss"
        content = "\n".join(
            [
                "; -----------------------------------------------------------------------------",
                "; Auto-generated by: make gen-inno-iss",
                "; Edit installer settings in project.mk, then regenerate this file.",
                "; -----------------------------------------------------------------------------",
                "",
                *(f'#define {name} "{_escape_inno(value)}"' for name, value in values.items()),
                "",
                layout.read_text(encoding="utf-8").replace("@VERSION_DEFINE@", version_define),
            ]
        )
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        print(f"Generated: {target}")
        return 0
    except OSError as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
